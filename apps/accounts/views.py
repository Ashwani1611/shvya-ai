def crm_signup_view(request):
    """
    Public SHVYA CRM signup.

    Signup creates:

        1. A new Organization
        2. The first User belonging to that Organization

    Organization:

        name       = company_name submitted by the user
        plan       = "free"
        is_active  = True
        created_at = automatically generated by Django

    User:

        name         = submitted name
        email        = submitted email
        phone        = submitted phone number
        organization = newly created organization
        role         = Admin
        is_active    = True
        password     = securely hashed
        created_at   = automatically generated by Django

    The user is NOT automatically logged into the CRM.

    After successful signup, the user is redirected to the
    CRM login page.
    """

    # --------------------------------------------------------
    # Already authenticated CRM users do not need signup.
    # --------------------------------------------------------

    if request.method == "GET":

        return render(
            request,
            "crm/signup.html",
        )

    # --------------------------------------------------------
    # Read submitted fields.
    # --------------------------------------------------------

    name = request.POST.get(
        "name",
        "",
    ).strip()

    email = request.POST.get(
        "email",
        "",
    ).strip()

    phone = request.POST.get(
        "phone",
        "",
    ).strip()

    company_name = request.POST.get(
        "company_name",
        "",
    ).strip()

    password = request.POST.get(
        "password",
        "",
    )

    # --------------------------------------------------------
    # Basic required-field validation.
    # --------------------------------------------------------

    errors = {}

    if not name:
        errors["name"] = "Name is required."

    if not email:
        errors["email"] = "Email is required."

    if not phone:
        errors["phone"] = "Phone number is required."

    if not company_name:
        errors["company_name"] = (
            "Company name is required."
        )

    if not password:
        errors["password"] = (
            "Password is required."
        )

    # --------------------------------------------------------
    # Normalize email.
    # --------------------------------------------------------

    if email:
        email = User.objects.normalize_email(
            email
        )

    # --------------------------------------------------------
    # Validate email format using Django's EmailValidator.
    # --------------------------------------------------------

    if email:

        from django.core.validators import validate_email

        try:

            validate_email(email)

        except ValidationError:

            errors["email"] = (
                "Enter a valid email address."
            )

    # --------------------------------------------------------
    # Password validation.
    # --------------------------------------------------------

    if password:

        try:

            password_validation.validate_password(
                password
            )

        except ValidationError as exc:

            errors["password"] = (
                " ".join(exc.messages)
            )

    # --------------------------------------------------------
    # Prevent signup with an already-used email.
    #
    # Although the database constraint is organization +
    # email, public signup should not create ambiguity by
    # allowing the same email to create multiple accounts.
    # --------------------------------------------------------

    if email:

        if User.objects.filter(
            email__iexact=email
        ).exists():

            errors["email"] = (
                "An account with this email address "
                "already exists."
            )

    # --------------------------------------------------------
    # Return form with validation errors.
    # --------------------------------------------------------

    if errors:

        return render(
            request,
            "crm/signup.html",
            {
                "errors": errors,
                "form_data": {
                    "name": name,
                    "email": email,
                    "phone": phone,
                    "company_name": company_name,
                },
            },
            status=400,
        )

    # --------------------------------------------------------
    # Create Organization + User atomically.
    #
    # If either creation fails, neither record remains in
    # the database.
    # --------------------------------------------------------

    try:

        with transaction.atomic():

            organization = Organization.objects.create(
                name=company_name,
                plan="free",
                is_active=True,
            )

            user = User.objects.create_user(
                email=email,
                organization=organization,
                password=password,
                name=name,
                phone=phone,
                role=User.Role.ADMIN,
                is_active=True,
                is_staff=False,
                is_superuser=False,
            )

    except IntegrityError:

        return render(
            request,
            "crm/signup.html",
            {
                "errors": {
                    "email": (
                        "An account with this email address "
                        "already exists."
                    )
                },
                "form_data": {
                    "name": name,
                    "email": email,
                    "phone": phone,
                    "company_name": company_name,
                },
            },
            status=400,
        )

    except Exception:

        return render(
            request,
            "crm/signup.html",
            {
                "errors": {
                    "general": (
                        "Unable to create your account "
                        "right now. Please try again."
                    )
                },
                "form_data": {
                    "name": name,
                    "email": email,
                    "phone": phone,
                    "company_name": company_name,
                },
            },
            status=500,
        )

    # --------------------------------------------------------
    # Success message.
    # --------------------------------------------------------

    messages.success(
        request,
        (
            "Your SHVYA AI account has been created "
            "successfully. Please log in to continue."
        ),
    )

    # --------------------------------------------------------
    # Redirect to CRM login.
    # --------------------------------------------------------

    return redirect(
        "crm-login"
    )


