# ============================================================


def crm_password_reset_view(
    request,
    uidb64,
    token,
):
    """
    Validate a password-reset token and allow the user to
    choose a new password.
    """

    # --------------------------------------------------------
    # Decode user ID.
    # --------------------------------------------------------

    try:

        uid = force_str(
            urlsafe_base64_decode(
                uidb64
            )
        )

        user = User.objects.get(
            pk=uid
        )

    except (
        TypeError,
        ValueError,
        OverflowError,
        User.DoesNotExist,
    ):

        user = None

    # --------------------------------------------------------
    # Validate reset token.
    # --------------------------------------------------------

    valid_link = (
        user is not None
        and user.is_active
        and not user.is_superuser
        and user.organization_id is not None
        and default_token_generator.check_token(
            user,
            token,
        )
    )

    # --------------------------------------------------------
    # Invalid / expired token
    # --------------------------------------------------------

    if not valid_link:

        return render(
            request,
            "crm/password_reset_invalid.html",
            status=400,
        )

    # --------------------------------------------------------
    # POST — save new password
    # --------------------------------------------------------

    if request.method == "POST":

        form = SetPasswordForm(
            user,
            request.POST,
        )

        if form.is_valid():

            form.save()

            return redirect(
                "crm-password-reset-complete"
            )

    else:

        form = SetPasswordForm(
            user
        )

    return render(
        request,
        "crm/reset_password.html",
        {
            "form": form,
        },
    )


