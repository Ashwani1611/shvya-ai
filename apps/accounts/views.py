def crm_logout_view(request):
    """
    Completely log the user out of the dedicated CRM session.

    This does NOT log the user out of:

        - Django Admin
        - SHVYA Superadmin
        - other SHVYA sessions

    It only destroys the dedicated CRM session:

        shvya_crm_sessionid

    After logout:

        /logout/
            ↓
        /dashboard/login/
            ↓
        CRM login page

    IMPORTANT:

    We deliberately flush the dedicated CRM session instead of
    only removing authentication keys.

    This guarantees that the previous CRM authentication state
    cannot remain inside the old session.
    """

    # =========================================================
    # LOAD CURRENT CRM SESSION
    # =========================================================

    crm_session = get_session_store(
        request,
        "dashboard",
    )

    # =========================================================
    # COMPLETELY DESTROY CRM SESSION
    # =========================================================
    #
    # flush():
    #
    #   1. creates a new empty session
    #   2. deletes the old session data
    #   3. removes the old authentication state
    #
    # This is stronger than simply doing:
    #
    #     session.pop("_auth_user_id")
    #
    # because the entire old CRM session is invalidated.
    #

    try:
        crm_session.flush()

    except Exception:
        # -----------------------------------------------------
        # Fallback
        # -----------------------------------------------------
        #
        # If flush() cannot complete, attempt to delete the
        # existing database-backed session.
        #

        try:
            crm_session.delete()

        except Exception:
            pass

    # =========================================================
    # REDIRECT TO CRM LOGIN PAGE
    # =========================================================
    #
    # IMPORTANT:
    #
    # Use the named CRM login URL.
    #
    # This resolves to:
    #
    #     /dashboard/login/
    #
    # through apps/crm/web_urls.py
    #

    response = redirect(
        "crm-login",
    )

    # =========================================================
    # DELETE CRM SESSION COOKIE
    # =========================================================
    #
    # This removes:
    #
    #     shvya_crm_sessionid
    #
    # from the browser.
    #

    delete_session_cookie(
        response,
        "dashboard",
    )

    # =========================================================
    # PREVENT DASHBOARD CACHING
    # =========================================================
    #
    # This is important after logout so that the browser does
    # not display a previously cached CRM dashboard when the
    # user navigates backward.
    #

    response["Cache-Control"] = (
        "no-cache, no-store, must-revalidate"
    )

    response["Pragma"] = "no-cache"
    response["Expires"] = "0"

    return response

