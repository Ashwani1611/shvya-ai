@ratelimit(
    key_func=lambda r: r.POST.get("email", "") if r.method == "POST" else "",
    limit=5,
    window=900,
    methods=("POST",),
)

def crm_forgot_password_view(request):
    """
    Start the CRM password-reset flow.

    Security:
        - Does not reveal whether an email exists.
        - Only active organization users are eligible.
        - Superadmin users cannot use the CRM password reset.
        - A secure Django password-reset token is generated.
        - The reset link expires automatically when the password
          changes.
    """

    if request.method == "POST":

        email = (
            request.POST.get(
                "email",
                "",
            )
            .strip()
            .lower()
        )

        # --------------------------------------------------------
        # Find active organization CRM user.
        # --------------------------------------------------------

        user = (
            User.objects
            .filter(
                email__iexact=email,
                is_active=True,
                is_superuser=False,
                organization__isnull=False,
            )
            .first()
        )

        # --------------------------------------------------------
        # Always continue to the same success page.
        #
        # This prevents account enumeration.
        # --------------------------------------------------------

        if user is not None:

            uid = urlsafe_base64_encode(
                force_bytes(
                    user.pk
                )
            )

            token = default_token_generator.make_token(
                user
            )

            reset_url = request.build_absolute_uri(
                reverse(
                    "crm-password-reset",
                    kwargs={
                        "uidb64": uid,
                        "token": token,
                    },
                )
            )

            # ----------------------------------------------------
            # Email subject
            # ----------------------------------------------------

            subject = "Reset your SHVYA CRM password"

            # ----------------------------------------------------
            # Plain-text email
            # ----------------------------------------------------

            message = f"""
Hello,

We received a request to reset your SHVYA CRM password.

Click the link below to create a new password:

{reset_url}

This link can only be used while it remains valid.

If you did not request a password reset, you can safely ignore
this email.

Regards,
SHVYA AI
""".strip()

            # ----------------------------------------------------
            # Send email
            # ----------------------------------------------------

            try:

                send_mail(
                    subject=subject,
                    message=message,
                    from_email=getattr(
                        settings,
                        "DEFAULT_FROM_EMAIL",
                        None,
                    ),
                    recipient_list=[
                        user.email
                    ],
                    fail_silently=False,
                )

            except Exception:

                # Log the error but do not reveal whether the
                # account exists to the browser.
                import logging

                logging.getLogger(
                    __name__
                ).exception(
                    "CRM password reset email failed."
                )

        return redirect(
            "crm-password-reset-sent"
        )

    return render(
        request,
        "crm/forgot_password.html",
    )


