@ratelimit(
    limit=10,
    window=3600,
    methods=("POST",),
)
def crm_signup_view(request):
    """
    Public SHVYA CRM signup.

    Signup creates:

        1. A new Organization
        2. The first User belonging to that Organization

    Organization:

        name       = company_name submitted by the user
        plan       = "free"
        is_active  = False until email verification
        created_at = automatically generated by Django

    User:

        name         = submitted name
        email        = submitted email
        phone        = submitted phone number
        organization = newly created organization
        role         = Agent
        is_active    = False until email verification
        password     = securely hashed
        created_at   = automatically generated by Django

    The user is NOT automatically logged into the CRM.

    After successful signup, the user is redirected to the
    CRM login page.
    """

    # --------------------------------------------------------
    # Already authenticated CRM users do not need signup.
    # --------------------------------------------------------

    if request.method == "GET":

        return render(
            request,
            "crm/signup.html",
        )

    # --------------------------------------------------------
    # Read submitted fields.
    # --------------------------------------------------------

    name = request.POST.get(
        "name",
        "",
    ).strip()

    email = request.POST.get(
        "email",
        "",
    ).strip()

    phone = request.POST.get(
        "phone",
        "",
    ).strip()

    company_name = request.POST.get(
        "company_name",
        "",
    ).strip()

    password = request.POST.get(
        "password",
        "",
    )

    # --------------------------------------------------------
    # Basic required-field validation.
    # --------------------------------------------------------

    errors = {}

    if not name:
        errors["name"] = "Name is required."

    if not email:
        errors["email"] = "Email is required."

    if not phone:
        errors["phone"] = "Phone number is required."

    if phone:
        try:
            phone = normalize_free_phone(phone)
        except ValidationError as exc:
            errors["phone"] = " ".join(exc.messages)

    if not company_name:
        errors["company_name"] = (
            "Company name is required."
        )

    if not password:
        errors["password"] = (
            "Password is required."
        )

    # --------------------------------------------------------
    # Normalize email.
    # --------------------------------------------------------

    if email:
        email = User.objects.normalize_email(
            email
        )

    # --------------------------------------------------------
    # Validate email format using Django's EmailValidator.
    # --------------------------------------------------------

    if email:

        from django.core.validators import validate_email

        try:

            validate_email(email)

        except ValidationError:

            errors["email"] = (
                "Enter a valid email address."
            )

    # --------------------------------------------------------
    # Password validation.
    # --------------------------------------------------------

    if password:

        try:

            password_validation.validate_password(
                password
            )

        except ValidationError as exc:

            errors["password"] = (
                " ".join(exc.messages)
            )

    # --------------------------------------------------------
    # Prevent signup with an already-used email.
    #
    # Although the database constraint is organization +
    # email, public signup should not create ambiguity by
    # allowing the same email to create multiple accounts.
    # --------------------------------------------------------

    if email:

        if User.objects.filter(
            email__iexact=email
        ).exists():

            errors["email"] = (
                "An account with this email address "
                "already exists."
            )

    # --------------------------------------------------------
    # Return form with validation errors.
    # --------------------------------------------------------

    if errors:

        return render(
            request,
            "crm/signup.html",
            {
                "errors": errors,
                "form_data": {
                    "name": name,
                    "email": email,
                    "phone": phone,
                    "company_name": company_name,
                },
            },
            status=400,
        )

    # --------------------------------------------------------
    # Create Organization + User atomically.
    #
    # If either creation fails, neither record remains in
    # the database.
    # --------------------------------------------------------

    try:

        with transaction.atomic():

            organization = Organization.objects.create(
                name=company_name,
                plan="free",
                package=Organization.Package.FREE,
                is_active=False,
            )

            user = User.objects.create_user(
                email=email,
                organization=organization,
                password=password,
                name=name,
                phone=phone,
                role=User.Role.AGENT,
                is_active=False,
                is_staff=False,
                is_superuser=False,
            )

            pipeline = organization.pipelines.get(name="Leads")
            pipeline.owner = user
            pipeline.country_code = "+91"
            pipeline.phone_number = phone[3:]
            pipeline.save(update_fields=["owner", "country_code", "phone_number", "updated_at"])

            delivery = SignupVerificationDelivery.objects.create(
                user=user,
                email=user.email,
                verification_endpoint=request.build_absolute_uri(reverse("crm-verify-email")),
            )
            transaction.on_commit(
                lambda: deliver_signup_verification(delivery.pk), robust=True,
            )

    except IntegrityError:

        return render(
            request,
            "crm/signup.html",
            {
                "errors": {
                    "email": (
                        "An account with this email address "
                        "already exists."
                    )
                },
                "form_data": {
                    "name": name,
                    "email": email,
                    "phone": phone,
                    "company_name": company_name,
                },
            },
            status=400,
        )

    except Exception as exc:
        logging.getLogger(__name__).error(
            "Signup account creation failed: error_type=%s", type(exc).__name__,
        )
        return render(
            request,
            "crm/signup.html",
            {
                "errors": {
                    "general": (
                        "Unable to create your account "
                        "right now. Please try again."
                    )
                },
                "form_data": {
                    "name": name,
                    "email": email,
                    "phone": phone,
                    "company_name": company_name,
                },
            },
            status=500,
        )

    # --------------------------------------------------------
    # Success message.
    # --------------------------------------------------------

    messages.success(
        request,
        (
            "Your SHVYA AI account has been created. "
            "Check your email and verify the address before logging in. "
            "If delivery is delayed, we will retry automatically."
        ),
    )

    # --------------------------------------------------------
    # Redirect to CRM login.
    # --------------------------------------------------------

    return redirect(
        "crm-login"
    )


@ratelimit(
    limit=30,
    window=3600,
    methods=("GET",),
)
def crm_verify_email_view(request):
    """Activate a pending signup after signed email ownership verification."""
    raw_token = request.GET.get("token", "").strip()
    if not raw_token:
        return HttpResponse("Invalid or missing verification token.", status=400)

    try:
        payload = signing.loads(
            raw_token,
            salt="shvya-signup-email-v1",
            max_age=86400,
        )
    except signing.SignatureExpired:
        return HttpResponse("This verification link has expired.", status=400)
    except signing.BadSignature:
        return HttpResponse("Invalid verification link.", status=400)

    user_id = str(payload.get("user_id") or "")
    organization_id = str(payload.get("organization_id") or "")
    email = str(payload.get("email") or "").strip().casefold()
    if not user_id or not organization_id or not email:
        return HttpResponse("Invalid verification link.", status=400)

    with transaction.atomic():
        user = (
            User.objects
            .select_for_update()
            .select_related("organization")
            .filter(pk=user_id, organization_id=organization_id)
            .first()
        )
        if user is None or user.email.casefold() != email:
            return HttpResponse("Invalid verification link.", status=400)

        organization = user.organization
        if user.is_superuser or user.role not in (User.Role.ADMIN, User.Role.AGENT):
            return HttpResponse("Invalid verification link.", status=400)

        if not user.is_active:
            user.is_active = True
            user.save(update_fields=["is_active", "updated_at"])
        if not organization.is_active:
            organization.is_active = True
            organization.save(update_fields=["is_active", "updated_at"])

    messages.success(
        request,
        "Email verified successfully. You can now log in to SHVYA AI.",
    )
    return redirect("crm-login")


