def one_time_login_view(request):
    """
    Authenticate a CRM user through a secure one-time login token.

    The CRM user is authenticated into the dedicated SHVYA CRM
    session instead of Django's default sessionid cookie.

    Session separation:

        /admin/       -> sessionid
        /superadmin/  -> shvya_superadmin_sessionid
        /dashboard/  -> shvya_crm_sessionid

    The one-time login token is:

        - hashed before lookup
        - validated for expiration
        - validated against the organization
        - validated against the user's active state
        - marked as used after successful validation
        - stored in the dedicated CRM session
    """

    # =========================================================
    # GET TOKEN
    # =========================================================

    raw_token = request.GET.get(
        "token",
        "",
    ).strip()

    if not raw_token:
        return HttpResponse(
            "Invalid or missing login token.",
            status=400,
        )

    # =========================================================
    # HASH TOKEN
    # =========================================================

    token_hash = hashlib.sha256(
        raw_token.encode("utf-8")
    ).hexdigest()

    # =========================================================
    # FIND TOKEN
    # =========================================================

    token = (
        OneTimeLoginToken.objects
        .select_related(
            "user",
            "organization",
        )
        .filter(
            token_hash=token_hash,
        )
        .first()
    )

    if token is None:
        return HttpResponse(
            "Invalid or expired login link.",
            status=400,
        )

    # =========================================================
    # VALIDATE TOKEN
    # =========================================================

    now = timezone.now()

    # ---------------------------------------------------------
    # Already used
    # ---------------------------------------------------------

    if token.used_at is not None:
        return HttpResponse(
            "This login link has already been used.",
            status=400,
        )

    # ---------------------------------------------------------
    # Expired
    # ---------------------------------------------------------

    if token.expires_at <= now:
        return HttpResponse(
            "This login link has expired.",
            status=400,
        )

    # =========================================================
    # VALIDATE USER
    # =========================================================

    user = token.user

    # ---------------------------------------------------------
    # User must be active
    # ---------------------------------------------------------

    if not user.is_active:
        return HttpResponse(
            "This user account is disabled.",
            status=403,
        )

    if not token.organization.is_active:
        return HttpResponse(
            "This organization account is disabled.",
            status=403,
        )

    # ---------------------------------------------------------
    # User organization must match token organization
    # ---------------------------------------------------------

    if user.organization_id != token.organization_id:
        return HttpResponse(
            "Invalid login token.",
            status=400,
        )

    # ---------------------------------------------------------
    # User must belong to an organization
    # ---------------------------------------------------------

    if user.organization_id is None:
        return HttpResponse(
            "This user is not associated with an organization.",
            status=400,
        )

    if not crm_user_is_authorized(user):
        return HttpResponse(
            "This CRM account is not authorized.",
            status=403,
        )

    # Atomically consume the token before creating an authenticated session.
    # Concurrent requests may both read the token, but only one can change the
    # unused row; every later request fails closed without receiving a session.
    consumed = OneTimeLoginToken.objects.filter(
        pk=token.pk,
        token_hash=token_hash,
        used_at__isnull=True,
        expires_at__gt=now,
    ).update(used_at=now)
    if consumed != 1:
        return HttpResponse(
            "This login link has already been used or expired.",
            status=400,
        )

    # =========================================================
    # LOAD DEDICATED CRM SESSION
    # =========================================================

    crm_session = get_session_store(
        request,
        "dashboard",
    )
    crm_session.cycle_key()

    # =========================================================
    # AUTHENTICATE USER INTO CRM SESSION
    # =========================================================
    #
    # The CRM uses its own session instead of Django's default
    # request.session authentication.
    #
    # This keeps:
    #
    #     Django Admin
    #     Superadmin
    #     CRM Dashboard
    #
    # independently authenticated.
    #

    set_authenticated_user(
        crm_session,
        user,
    )

    # =========================================================
    # REDIRECT TO CRM DASHBOARD
    # =========================================================

    response = redirect(
        "/dashboard/",
    )

    # =========================================================
    # SAVE DEDICATED CRM COOKIE
    # =========================================================

    save_session_cookie(
        request,
        response,
        crm_session,
        "dashboard",
    )

    # =========================================================
    # PREVENT CACHED LOGIN RESPONSE
    # =========================================================

    response["Cache-Control"] = (
        "no-cache, no-store, must-revalidate"
    )

    response["Pragma"] = "no-cache"
    response["Expires"] = "0"

    return response


